#!/usr/bin/env bun
/**
 * assistant-setup — bootstrap wizard for the galiprandi/assistant template.
 *
 * Compiled to a single binary via `bun build --compile` (see the
 * `build:wizard` script). Zero prerequisites: no Node, no git.
 *
 * Steps:
 *  1. Preflight: detect agent CLIs in PATH.
 *  2. Target dir prompt.
 *  3. Download + extract the template tarball.
 *  4. Best-effort login-state detection per agent.
 *  5. Optional Telegram channel → writes acp-connector.jsonc.
 *  6. Optional autostart via the OS-native mechanism (opt-in, default OFF).
 *  7. Handoff: spawn the agent on the template's setup skill.
 */
import { spawn, spawnSync } from 'node:child_process';
import {
  createWriteStream,
  existsSync,
  mkdirSync,
  renameSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { homedir, platform, tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { createInterface, type Interface } from 'node:readline';
import { pipeline } from 'node:stream/promises';
import { type DetectedAgent, defaultWhich, detectAgents, KNOWN_AGENTS } from './agents.js';
import { installDaemon } from './daemon.js';

const TEMPLATE_TARBALL = 'https://github.com/galiprandi/assistant/archive/refs/heads/main.tar.gz';
const SETUP_PROMPT = 'Read AGENTS.md and run the setup skill in .agents/skills/setup/SKILL.md';

function ask(rl: Interface, prompt: string): Promise<string> {
  return new Promise((res) => rl.question(prompt, (a) => res(a.trim())));
}

async function askYesNo(rl: Interface, prompt: string, defaultYes = false): Promise<boolean> {
  const suffix = defaultYes ? ' [Y/n] ' : ' [y/N] ';
  const answer = (await ask(rl, prompt + suffix)).toLowerCase();
  if (!answer) return defaultYes;
  return answer === 'y' || answer === 'yes';
}

function step(n: number, title: string): void {
  console.log(`\n── Step ${n}: ${title} ${'─'.repeat(Math.max(2, 50 - title.length))}\n`);
}

async function downloadAndExtract(targetDir: string): Promise<void> {
  const tgz = join(tmpdir(), `assistant-template-${Date.now()}.tar.gz`);
  console.log(`Downloading ${TEMPLATE_TARBALL}`);
  const res = await fetch(TEMPLATE_TARBALL, { redirect: 'follow' });
  if (!res.ok || !res.body) throw new Error(`Download failed: HTTP ${res.status}`);
  await pipeline(res.body as unknown as NodeJS.ReadableStream, createWriteStream(tgz));

  const extractDir = join(tmpdir(), `assistant-extract-${Date.now()}`);
  mkdirSync(extractDir, { recursive: true });
  const tar = spawnSync('tar', ['-xzf', tgz, '-C', extractDir], { stdio: 'inherit' });
  if (tar.status !== 0) {
    rmSync(tgz, { force: true });
    throw new Error('tar extraction failed — is `tar` available on this system?');
  }
  renameSync(join(extractDir, 'assistant-main'), targetDir);
  rmSync(tgz, { force: true });
  rmSync(extractDir, { recursive: true, force: true });
}

function writeConnectorConfig(targetDir: string, agentCmd: string, tgToken: string): void {
  const config = `{
  // Generated by assistant-setup. Edit to taste; see acp-connector docs.
  "agentCmd": "${agentCmd}",
  "platforms": {
    "telegram": { "token": "${tgToken}", "allowedChatIds": [] }
  }
}
`;
  writeFileSync(join(targetDir, 'acp-connector.jsonc'), config);
}

function handoff(agent: DetectedAgent, targetDir: string): void {
  const args = agent.spec.nonInteractiveArgs(SETUP_PROMPT);
  if (!args) {
    console.log(`\n${agent.spec.name} has no known one-shot mode — launching it interactively.`);
    console.log('Paste this prompt when it starts:\n');
    console.log(`  ${SETUP_PROMPT}\n`);
    spawn(agent.path, [], { cwd: targetDir, stdio: 'inherit' });
    return;
  }
  console.log(`\nHanding off to ${agent.spec.name}: ${agent.spec.bin} ${args.join(' ')}`);
  spawn(agent.path, args, { cwd: targetDir, stdio: 'inherit' });
}

function installOpencode(): boolean {
  console.log('Installing OpenCode...');
  const r =
    platform() === 'win32'
      ? spawnSync('powershell', ['-c', 'irm opencode.ai/install.ps1 | iex'], { stdio: 'inherit' })
      : spawnSync('sh', ['-c', 'curl -fsSL https://opencode.ai/install | bash'], {
          stdio: 'inherit',
        });
  return r.status === 0;
}

function installBunAndShim(): boolean {
  if (platform() === 'win32') return false; // bun.ps1 path; documented instead
  const home = homedir();
  const r = spawnSync('sh', ['-c', 'curl -fsSL https://bun.sh/install | bash'], {
    stdio: 'inherit',
  });
  if (r.status !== 0) return false;
  const bunBin = join(home, '.bun', 'bin', 'bun');
  if (!existsSync(bunBin)) return false;
  const localBin = join(home, '.local', 'bin');
  mkdirSync(localBin, { recursive: true });
  const shim = join(localBin, 'node');
  writeFileSync(shim, `#!/bin/sh\nexec "${bunBin}" "$@"\n`);
  spawnSync('chmod', ['+x', shim]);
  console.log(`  ✓ bun installed; node shim -> ${shim} (add ~/.local/bin to PATH)`);
  return true;
}

export async function wizard(): Promise<void> {
  const rl = createInterface({ input: process.stdin, output: process.stdout });

  console.log('assistant-setup');
  console.log('═══════════════════════════════════════════════════════════');
  console.log('Bootstrap a personal AI assistant — no Node or git needed.');
  console.log('═══════════════════════════════════════════════════════════');

  // Step 1: preflight — detect agent CLIs.
  step(1, 'Detecting agent CLIs');
  let found = detectAgents(defaultWhich(platform()));
  if (found.length === 0) {
    console.log('No supported agent CLI found in PATH.');
    console.log('An agent runtime is required — it powers the assistant.');
    const install = await ask(
      rl,
      'Install OpenCode now? It is free/open-source and includes free models (no API key needed) [Y/n] '
    );
    if (install.toLowerCase() === 'n') {
      console.log('Install any of these and re-run the wizard:');
      for (const a of KNOWN_AGENTS) console.log(`  • ${a.name}: ${a.installUrl}`);
      rl.close();
      process.exit(0);
    }
    if (installOpencode()) {
      // The installer updates the shell rc PATH, not ours — add the known
      // install dirs so re-detection finds the fresh binary.
      const home = homedir();
      process.env.PATH = `${join(home, '.opencode', 'bin')}:${process.env.PATH}`;
      found = detectAgents(defaultWhich(platform()));
    }
    if (found.length === 0) {
      console.log('! OpenCode install did not complete — install it manually: https://opencode.ai');
      rl.close();
      process.exit(1);
    }
  }
  for (const a of found) {
    const login = a.looksLoggedIn ? ' (looks logged in)' : '';
    console.log(`  ✓ ${a.spec.name.padEnd(14)} ${a.path}${login}`);
  }

  let selected = found[0];
  if (found.length > 1) {
    const pick = await ask(rl, `Multiple agents found. Use which? [${selected.spec.bin}] `);
    const chosen = found.find(
      (a) => a.spec.bin === pick || a.spec.name.toLowerCase() === pick.toLowerCase()
    );
    if (chosen) selected = chosen;
  }
  console.log(`Using: ${selected.spec.name}`);

  // Chrome check — browser-automation drives a system Chrome via agent-browser.
  const chromeBin = [
    'google-chrome',
    'google-chrome-stable',
    'chromium',
    'chromium-browser',
    'chrome',
  ]
    .map((b) => defaultWhich(platform())(b))
    .find(Boolean);
  if (chromeBin) {
    console.log(`  ✓ Chrome         ${chromeBin}`);
  } else {
    console.log('  ! Chrome not found — browser automation needs a system Chrome.');
    console.log('    Install it when the agent asks for web access (google-chrome or chromium).');
  }

  // Step 2: target dir.
  step(2, 'Install location');
  const dirAnswer = await ask(rl, `Install directory? [${join(homedir(), 'my-assistant')}] `);
  const targetDir = resolve(dirAnswer || join(homedir(), 'my-assistant'));
  if (existsSync(targetDir)) {
    console.error(`\n${targetDir} already exists — aborting to keep it safe.`);
    rl.close();
    process.exit(1);
  }

  // Step 3: download + extract template.
  step(3, 'Downloading template');
  await downloadAndExtract(targetDir);
  console.log(`Template installed to ${targetDir}`);

  // Step 4: login-state recap.
  step(4, 'Agent login check');
  if (selected.looksLoggedIn) {
    console.log(`${selected.spec.name} looks logged in — good to go.`);
  } else {
    console.log(`! ${selected.spec.name} may not be logged in yet.`);
    console.log('  If the handoff below fails, run its login command first.');
  }

  // Step 5: optional Telegram channel.
  step(5, 'Messaging channel (optional)');
  if (await askYesNo(rl, 'Connect a Telegram bot?', false)) {
    console.log('Create a bot via @BotFather on Telegram, then paste the token.');
    const token = await ask(rl, 'Telegram bot token: ');
    if (token) {
      writeConnectorConfig(targetDir, selected.spec.agentCmd, token);
      console.log('Wrote acp-connector.jsonc (allowedChatIds empty — fill after first /start).');
    }
  } else {
    console.log('Skipped — you can add Telegram/Discord later with `acp-connector setup`.');
  }

  // Step 6: autostart (explicit opt-in only).
  step(6, 'Autostart on boot');
  if (await askYesNo(rl, 'Start the assistant automatically when this computer boots?', false)) {
    try {
      const r = installDaemon(platform(), { targetDir, command: 'npx acp-connector start' });
      console.log(`Installed via ${r.mechanism}: ${r.detail}`);
    } catch (err) {
      console.log(`Could not install autostart: ${(err as Error).message}`);
      console.log('You can set it up later — see README.');
    }
  } else {
    console.log('Skipped (default). Run the assistant manually whenever you like.');
  }

  rl.close();

  // Node-less machines: the template scripts call `node` — offer a bun shim.
  if (!defaultWhich(platform())('node')) {
    step(7, 'Runtime shim');
    const shim = await ask(
      rl,
      'No Node.js found. Assistant scripts need a JS runtime — install bun (single binary) and create a `node` shim? [Y/n] '
    );
    if (shim.toLowerCase() !== 'n') {
      if (!installBunAndShim())
        console.log('  ! bun install failed — run manually: https://bun.sh');
    }
  }

  // Step 8: handoff to the agent on the template's setup skill.
  step(8, 'Handoff to your agent');
  handoff(selected, targetDir);
}

// Run only when executed directly (not imported by tests).
const isMain =
  (import.meta as { main?: boolean }).main === true ||
  process.argv[1]?.endsWith('wizard.ts') === true;
if (isMain) {
  wizard().catch((err) => {
    console.error(`\nSetup failed: ${(err as Error).message}`);
    process.exit(1);
  });
}
